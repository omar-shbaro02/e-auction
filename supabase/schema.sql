create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  "fullName" text not null default '',
  email text not null unique,
  role text not null default 'buyer' check (role in ('buyer', 'admin')),
  phone text not null default '',
  company text not null default '',
  address text not null default '',
  city text not null default '',
  state text not null default '',
  "postalCode" text not null default '',
  country text not null default '',
  "cardName" text not null default '',
  "cardNumber" text not null default '',
  "cardExpiry" text not null default '',
  "cardCvv" text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.items (
  auction_id bigint generated by default as identity unique,
  slug text primary key,
  title text not null,
  category text not null,
  summary text not null,
  mode text not null check (mode in ('auction', 'buy-now', 'hybrid')),
  status text not null default 'draft' check (status in ('draft', 'scheduled', 'live', 'closed', 'sold', 'archived')),
  location text not null,
  shipping text not null,
  "currentBid" numeric,
  "buyNowPrice" numeric,
  minimum_bid numeric,
  reserve_price numeric,
  starts_at timestamptz,
  ends_at timestamptz,
  "endsIn" text,
  stock integer not null default 1,
  grade text not null,
  gradient text not null,
  highlights jsonb not null default '[]'::jsonb,
  "seoDescription" text not null,
  currency_code text not null default 'USD',
  "bidIncrement" numeric,
  "bidCount" integer,
  watchers integer,
  "reserveMet" boolean,
  seller text,
  "lotNumber" text,
  created_by_email text,
  updated_by_email text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles
