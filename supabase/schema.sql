do $$
begin
  if not exists (
    select 1
    from pg_policies
    where schemaname = 'public' and tablename = 'items' and policyname = 'Public read items'
  ) then
    create policy "Public read items" on public.items for select using (true);
  end if;

  if not exists (
    select 1
    from pg_policies
    where schemaname = 'public' and tablename = 'profiles' and policyname = 'Users read own profile'
  ) then
    create policy "Users read own profile" on public.profiles
      for select using (auth.uid() = id);
  end if;

  if not exists (
    select 1
    from pg_policies
    where schemaname = 'public' and tablename = 'profiles' and policyname = 'Users update own profile'
  ) then
    create policy "Users update own profile" on public.profiles
      for update using (auth.uid() = id);
  end if;

  if not exists (
    select 1
    from pg_policies
    where schemaname = 'public' and tablename = 'profiles' and policyname = 'Admins read profiles'
  ) then
    create policy "Admins read profiles" on public.profiles
      for select using (
        exists (
          select 1
          from public.profiles admin_profile
          where admin_profile.id = auth.uid() and admin_profile.role = 'admin'
        )
      );
  end if;

  if not exists (
    select 1
    from pg_policies
    where schemaname = 'public' and tablename = 'bids' and policyname = 'Users read bids'
  ) then
    create policy "Users read bids" on public.bids for select using (true);
  end if;

  if not exists (
    select 1
    from pg_policies
    where schemaname = 'public' and tablename = 'bids' and policyname = 'Users insert own bids'
  ) then
    create policy "Users insert own bids" on public.bids
      for insert with check (auth.uid() = user_id);
  end if;

  if not exists (
    select 1
    from pg_policies
    where schemaname = 'public' and tablename = 'item_assets' and policyname = 'Public read item assets'
  ) then
    create policy "Public read item assets" on public.item_assets for select using (true);
  end if;

  if not exists (
    select 1
    from pg_policies
    where schemaname = 'public' and tablename = 'orders' and policyname = 'Users read own orders'
  ) then
    create policy "Users read own orders" on public.orders
      for select using (auth.uid() = user_id);
  end if;

  if not exists (
    select 1
    from pg_policies
    where schemaname = 'public' and tablename = 'order_items' and policyname = 'Users read own order items'
  ) then
    create policy "Users read own order items" on public.order_items
      for select using (
        exists (
          select 1
          from public.orders o
          where o.id = order_id and o.user_id = auth.uid()
        )
      );
  end if;
end $$;
