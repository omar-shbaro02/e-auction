do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'profiles_role_check'
  ) then
    alter table public.profiles
      add constraint profiles_role_check check (role in ('buyer', 'admin'));
  end if;

  if not exists (
    select 1
    from pg_constraint
    where conname = 'items_status_check'
  ) then
    alter table public.items
      add constraint items_status_check
      check (status in ('draft', 'scheduled', 'live', 'closed', 'sold', 'archived'));
  end if;

  if not exists (
    select 1
    from pg_constraint
    where conname = 'items_auction_id_key'
  ) then
    alter table public.items add constraint items_auction_id_key unique (auction_id);
  end if;
end $$;

create table if not exists public.bids (
  id uuid primary key default gen_random_uuid(),
  item_slug text not null references public.items (slug) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  amount numeric not null,
  max_amount numeric,
  status text not null default 'active' check (status in ('active', 'winning', 'outbid', 'cancelled')),
  created_at timestamptz not null default now()
);

create table if not exists public.item_assets (
  id uuid primary key default gen_random_uuid(),
  item_slug text not null references public.items (slug) on delete cascade,
  asset_url text not null,
  alt_text text not null default '',
  sort_order integer not null default 0,
  is_primary boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles (id) on delete restrict,
  status text not null default 'pending' check (status in ('pending', 'authorized', 'paid', 'failed', 'fulfilled', 'cancelled', 'refunded')),
  order_type text not null default 'auction-win' check (order_type in ('auction-win', 'buy-now', 'manual')),
  subtotal numeric not null default 0,
  currency_code text not null default 'USD',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders (id) on delete cascade,
  item_slug text not null references public.items (slug) on delete restrict,
  quantity integer not null default 1,
  unit_price numeric not null,
  created_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
  id uuid primary key default gen_random_uuid(),
  actor_email text,
  actor_user_id uuid references public.profiles (id) on delete set null,
  entity_type text not null,
  entity_id text not null,
  action text not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.bids
  add column if not exists max_amount numeric;

alter table public.bids
  add column if not exists status text not null default 'active';

create index if not exists bids_item_slug_created_at_idx on public.bids (item_slug, created_at desc);
create index if not exists bids_user_id_created_at_idx on public.bids (user_id, created_at desc);
create index if not exists item_assets_item_slug_sort_order_idx on public.item_assets (item_slug, sort_order asc);
create index if not exists orders_user_id_created_at_idx on public.orders (user_id, created_at desc);
create index if not exists audit_logs_entity_idx on public.audit_logs (entity_type, entity_id, created_at desc);
create index if not exists items_mode_idx on public.items (mode);
create index if not exists items_category_idx on public.items (category);
create index if not exists items_status_idx on public.items (status);
create index if not exists items_starts_at_idx on public.items (starts_at);
create index if not exists items_ends_at_idx on public.items (ends_at);

